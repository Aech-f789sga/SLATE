import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.route('https://fonts.googleapis.com/**', (r) => r.abort());
await page.goto('http://127.0.0.1:3000/', { waitUntil: 'domcontentloaded' });
await page.waitForSelector('#grid', { timeout: 20000 });
await page.waitForTimeout(1200);
await page.evaluate(() => { const n={id:Date.now(),name:'P',upd:Date.now(),pages:[{tpl:'lined',col:'',strokes:[],pw:800,ph:1100}]}; window.lib.push(n); window.openNotebook(n); });
await page.waitForTimeout(1500);
console.log(await page.evaluate(() => [...document.querySelectorAll('#ink-pen > *, .ink-sheet, #ink-pop, #ink-penset, #ink-erset, #sh-pick, #acc-pop')].map(n => `${n.tagName.toLowerCase()}${n.id?'#'+n.id:''}${n.dataset&&n.dataset.k?'[k='+n.dataset.k+']':''}`)));
await browser.close();
