import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.route('https://fonts.googleapis.com/**', (r) => r.abort());
await page.goto('http://127.0.0.1:3000/', { waitUntil: 'domcontentloaded' });
await page.waitForSelector('#grid', { timeout: 20000 });
await page.waitForTimeout(1200);
await page.evaluate(() => { const n={id:Date.now(),name:'R',upd:Date.now(),pages:[{tpl:'lined',col:'',strokes:[],pw:800,ph:1100}]}; window.lib.push(n); window.openNotebook(n); });
await page.waitForTimeout(1500);
await page.evaluate(() => { const b=[...document.querySelectorAll('button')].find(x=>/skip tour/i.test(x.textContent||'')); b?.click(); document.getElementById('tour-root')?.remove(); });
await page.waitForTimeout(400);
await page.click('#pgm');
await page.waitForTimeout(600);
const card = await page.evaluate(() => { const b = document.getElementById('bar2').getBoundingClientRect(); return { l: Math.round(b.left), t: Math.round(b.top), w: Math.round(b.width), h: Math.round(b.height) }; });
console.log('card', JSON.stringify(card));
await page.screenshot({ path: 'shots/desk-pgm-open.png', clip: { x: 380, y: 60, width: 700, height: 340 } });
// outside press closes
await page.mouse.click(1200, 700);
await page.waitForTimeout(300);
console.log('closed by outside press', await page.evaluate(() => !document.getElementById('bar2').classList.contains('open')));
await browser.close();
